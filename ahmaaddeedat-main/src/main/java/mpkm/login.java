private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {

    String username = jTextUsername.getText().trim();
    String password = jTextPassword.getText().trim();

    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Username dan password wajib diisi!"
        );
        return;
    }

    String url = "jdbc:mysql://localhost:3306/mpkm";

    try (
        java.sql.Connection conn =
            java.sql.DriverManager.getConnection(url, "root", "");

        java.sql.PreparedStatement ps = conn.prepareStatement(
            "SELECT * FROM user WHERE username = ? AND password = ?"
        )
    ) {
        ps.setString(1, username);
        ps.setString(2, password);

        try (java.sql.ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Login berhasil! Selamat datang, " + username
                );
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Username atau password salah!"
                );
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Terjadi kesalahan: " + e.getMessage()
        );
    }
} 
